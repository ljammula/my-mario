/**
 * SpriteData.ts
 * All NES-accurate sprite pixel data encoded as RLE (run-length encoding).
 * Format: alternating [count, paletteIndex] pairs, left-to-right, top-to-bottom.
 * 0 = transparent.
 *
 * NES Palette:
 *  0:#000000  1:#7C7C7C  2:#BCBCBC  3:#FFFFFF
 *  4:#8C0000  5:#FC0000  6:#F87858
 *  7:#503000  8:#AC7C00  9:#FC7C00
 * 10:#FCFC00 11:#FCFC7C
 * 12:#006000 13:#00A800 14:#A8FC00
 * 15:#005858 16:#00FCFC
 * 17:#000080 18:#0000FC 19:#6060FC 20:#6888FC
 * 21:#7C00FC 22:#FC00FC 23:#FC88FC
 * 24:#FCBCB0 25:#AC5028
 */

// ── RLE decoder ──────────────────────────────────────────────────────────────

export function decodeRLE(rle: number[], width: number, height: number): number[][] {
  const pixels: number[][] = [];
  let row: number[] = [];
  for (let i = 0; i < rle.length; i += 2) {
    const count = rle[i];
    const color = rle[i + 1];
    for (let j = 0; j < count; j++) {
      row.push(color);
      if (row.length === width) {
        pixels.push(row);
        row = [];
      }
    }
  }
  return pixels;
}

